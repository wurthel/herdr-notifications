func TestClaudePromptForms(t *testing.T) {
	tests := []struct {
		name    string
		content any
		want    string
	}{
		{"plain string", "  fix the bug  ", "fix the bug"},
		{
			"slash command with args",
			"<command-name>/plan</command-name>\n<command-message>plan</command-message>\n<command-args>do X</command-args>",
			"/plan do X",
		},
		{
			"slash command without args",
			"<command-message>clear</command-message>\n<command-name>/clear</command-name>\n<command-args></command-args>",
			"/clear",
		},
		{"bash input", "<bash-input>ls -la</bash-input>", "! ls -la"},
		{
			"text blocks and image",
			[]obj{cText("look at this"), {"type": "image", "source": obj{"type": "base64", "data": "AAAA"}}, cText("and fix it")},
			"look at this\nand fix it",
		},
		{"multiline", "line one\nline two", "line one\nline two"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			checkTurn(t, readFixture(t, "claude", cUser(tt.content)), Turn{Prompt: tt.want})
		})
	}
}

