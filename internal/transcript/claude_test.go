func TestClaudeOutput(t *testing.T) {
	tests := []struct {
		name    string
		entries []any
		want    string
	}{
		{
			name: "split message joined",
			entries: []any{
				cAssistant("msg_1", cText("one")),
				cAssistant("msg_1", cToolUse("toolu_1", "Read", obj{"file_path": "/a"})),
				cToolResult("toolu_1"),
				cAssistant("msg_1", cText("two")),
			},
			want: "one\n\ntwo",
		},
		{
			name: "later message replaces earlier",
			entries: []any{
				cAssistant("msg_1", cText("old")),
				cAssistant("msg_2", cText("new")),
			},
			want: "new",
		},
		{
			name: "message without text keeps previous",
			entries: []any{
				cAssistant("msg_1", cText("kept")),
				cAssistant("msg_2", obj{"type": "thinking", "thinking": "..."}),
				cAssistant("msg_2", cText("   ")),
				cAssistant("msg_3", cToolUse("toolu_1", "Bash", obj{"command": "ls"})),
				cToolResult("toolu_1"),
			},
			want: "kept",
		},
		{
			name: "same id after another message is not appended",
			entries: []any{
				cAssistant("msg_1", cText("a")),
				cAssistant("msg_2", cText("b")),
				cAssistant("msg_1", cText("c")),
			},
			want: "c",
		},
		{
			name: "empty ids never join",
			entries: []any{
				cAssistant("", cText("a")),
				cAssistant("", cText("b")),
			},
			want: "b",
		},
		{
			name: "text trimmed",
			entries: []any{
				cAssistant("msg_1", cText("\n\n  answer \n")),
			},
			want: "answer",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			entries := append([]any{cUser("prompt")}, tt.entries...)
			checkTurn(t, readFixture(t, "claude", entries...), Turn{Prompt: "prompt", Output: tt.want})
		})
	}
}

