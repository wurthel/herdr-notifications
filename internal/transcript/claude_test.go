func TestClaudeParallelToolCalls(t *testing.T) {
	got := readFixture(t, "claude",
		map[string]any{"type": "user", "message": map[string]any{"role": "user", "content": "go"}},
		map[string]any{"type": "assistant", "message": map[string]any{"id": "m1", "role": "assistant", "content": []map[string]any{
			{"type": "tool_use", "id": "a", "name": "Bash", "input": map[string]any{"command": "first"}},
			{"type": "tool_use", "id": "b", "name": "Bash", "input": map[string]any{"command": "second"}},
		}}},
		map[string]any{"type": "user", "message": map[string]any{"role": "user", "content": []map[string]any{{"type": "tool_result", "tool_use_id": "b"}}}},
	)
	if got.Pending != "Bash: first" {
		t.Errorf("Pending = %q, want the still-unanswered first call", got.Pending)
	}
}
