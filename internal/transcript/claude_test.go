func TestClaudePending(t *testing.T) {
	tests := []struct {
		name  string
		tool  obj
		want  string
		reply bool
	}{
		{name: "answered", tool: cToolUse("toolu_1", "Bash", obj{"command": "ls"}), reply: true},
		{name: "bash", tool: cToolUse("toolu_1", "Bash", obj{"command": "  rm -rf build  ", "description": "clean"}), want: "Bash: rm -rf build"},
		{
			name: "ask user question",
			tool: cToolUse("toolu_1", "AskUserQuestion", obj{"questions": []obj{
				{"question": "Which database?", "options": []obj{{"label": "Postgres"}, {"label": "SQLite"}, {"description": "no label"}}},
				{"question": "Deploy now?", "options": []obj{{"label": "Yes"}}},
			}}),
			want: "Which database?\n• Postgres\n• SQLite\nDeploy now?\n• Yes",
		},
		{name: "ask user question without questions", tool: cToolUse("toolu_1", "AskUserQuestion", obj{}), want: "AskUserQuestion"},
		{name: "exit plan mode", tool: cToolUse("toolu_1", "ExitPlanMode", obj{"plan": "# Plan\n1. do it"}), want: "Plan approval"},
		{name: "unknown tool with file path", tool: cToolUse("toolu_1", "Edit", obj{"file_path": "/src/main.go", "old_string": "a"}), want: "Edit: /src/main.go"},
		{name: "unknown tool with url", tool: cToolUse("toolu_1", "WebFetch", obj{"url": "https://x.test"}), want: "WebFetch: https://x.test"},
		{name: "unknown tool with nothing", tool: cToolUse("toolu_1", "mcp__thing__do", obj{"n": 1}), want: "mcp__thing__do"},
		{name: "unknown tool with null input", tool: obj{"type": "tool_use", "id": "toolu_1", "name": "Mystery"}, want: "Mystery"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			entries := []any{
				cUser("prompt"),
				cAssistant("msg_1", cText("Let me check.")),
				cAssistant("msg_1", tt.tool),
			}
			if tt.reply {
				entries = append(entries, cToolResult("toolu_1"))
			}
			checkTurn(t, readFixture(t, "claude", entries...), Turn{Prompt: "prompt", Output: "Let me check.", Pending: tt.want})
		})
	}
}

