package transcript

import "testing"

func cUser(content any) obj {
	return obj{
		"type": "user", "isSidechain": false, "isMeta": false,
		"message": obj{"role": "user", "content": content},
	}
}

func cMeta(content any) obj {
	e := cUser(content)
	e["isMeta"] = true
	return e
}

func cSidechain(e obj) obj {
	e["isSidechain"] = true
	return e
}

func cAssistant(id string, blocks ...obj) obj {
	return obj{
		"type": "assistant", "isSidechain": false,
		"message": obj{"id": id, "role": "assistant", "content": blocks},
	}
}

func cText(s string) obj { return obj{"type": "text", "text": s} }

func cToolUse(id, name string, input obj) obj {
	return obj{"type": "tool_use", "id": id, "name": name, "input": input}
}

func cToolResult(id string) obj {
	return cUser([]obj{{"type": "tool_result", "tool_use_id": id, "content": "done"}})
}

var claudeNoise = []any{
	obj{"type": "attachment", "attachment": obj{"type": "file", "content": "x"}},
	obj{"type": "last-prompt", "lastPrompt": "ignored prompt"},
	obj{"type": "system", "subtype": "local_command", "content": "system text", "message": obj{"role": "user", "content": "noise"}},
	obj{"type": "file-history-snapshot", "snapshot": obj{}},
	obj{"type": "permission-mode", "mode": "plan"},
}

func TestClaudeBasicTurn(t *testing.T) {
	entries := append([]any{}, claudeNoise...)
	entries = append(entries,
		cUser("first prompt"),
		cAssistant("msg_1", cText("first answer")),
		cUser("second prompt"),
		cAssistant("msg_2", obj{"type": "thinking", "thinking": "hmm"}),
		cAssistant("msg_2", cText("Part one.")),
		cAssistant("msg_2", cToolUse("toolu_1", "Bash", obj{"command": "ls"})),
		cToolResult("toolu_1"),
		cAssistant("msg_3", cText("Final answer."), cText("More detail.")),
	)
	entries = append(entries, claudeNoise...)
	checkTurn(t, readFixture(t, "claude", entries...), Turn{
		Prompt: "second prompt",
		Output: "Final answer.\n\nMore detail.",
	})
}

func TestClaudeSkipsSyntheticPrompts(t *testing.T) {
	skipped := []any{
		cMeta("meta text"),
		cSidechain(cUser("subagent prompt")),
		cUser("<task-notification>\n<task-id>1</task-id>\n<status>completed</status>\n</task-notification>"),
		cUser("<local-command-caveat>Caveat: generated by local commands</local-command-caveat>\n<local-command-stdout>output</local-command-stdout>"),
		cUser("<system-reminder>remember this</system-reminder>"),
		cUser("[Request interrupted by user]"),
		cUser("[Request interrupted by user for tool use]"),
		cUser("   "),
		cUser([]obj{{"type": "image", "source": obj{"type": "base64"}}}),
	}
	for i, e := range skipped {
		entries := []any{cUser("real prompt"), cAssistant("msg_1", cText("answer")), e}
		checkTurn(t, readFixture(t, "claude", entries...), Turn{Prompt: "real prompt", Output: "answer"})
		if t.Failed() {
			t.Fatalf("entry %d was not skipped: %v", i, e)
		}
	}
}

